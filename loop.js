

// Цикл від 0 до 9 (включно), виводимо ітератор на кожній ітерації
console.log('--- Цикл від 0 до 9 ---');
for (let i = 0; i <= 9; i++) {
  console.log(`Ітерація: ${i}`);
}

// Цикл від 100 до 0 з кроком 10
console.log('\n--- Цикл від 100 до 0 з кроком 10 ---');
for (let i = 100; i >= 0; i -= 10) {
  console.log(`Ітерація: ${i}`);
}
